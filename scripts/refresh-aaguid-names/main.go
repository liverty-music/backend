// Command refresh-aaguid-names rewrites internal/entity/passkey_provider_names.go
// from the passkeydeveloper/passkey-authenticator-aaguids list: it reads the
// current commit of the list's default branch, downloads aaguid.json at that
// commit and keeps only each entry's name (the icons are not copied). Run it
// with `make refresh-aaguid-names` and review the diff.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"
)

const (
	repo   = "passkeydeveloper/passkey-authenticator-aaguids"
	output = "internal/entity/passkey_provider_names.go"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "refresh-aaguid-names:", err)
		os.Exit(1)
	}
}

func run() error {
	client := &http.Client{Timeout: 30 * time.Second}

	var commit struct {
		SHA string `json:"sha"`
	}
	if err := getJSON(client, "https://api.github.com/repos/"+repo+"/commits/main", &commit); err != nil {
		return fmt.Errorf("read the list's commit: %w", err)
	}
	if commit.SHA == "" {
		return fmt.Errorf("the list's commit has no sha")
	}

	var entries map[string]struct {
		Name string `json:"name"`
	}
	if err := getJSON(client, "https://raw.githubusercontent.com/"+repo+"/"+commit.SHA+"/aaguid.json", &entries); err != nil {
		return fmt.Errorf("download aaguid.json: %w", err)
	}

	aaguids := make([]string, 0, len(entries))
	for aaguid := range entries {
		aaguids = append(aaguids, aaguid)
	}
	slices.Sort(aaguids)

	var b strings.Builder
	b.WriteString("// Code generated by scripts/refresh-aaguid-names (make refresh-aaguid-names); DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: https://github.com/%s/blob/%s/aaguid.json (names only; icons are not copied).\n\n", repo, commit.SHA)
	b.WriteString("package entity\n\n")
	b.WriteString("// passkeyProviderNames maps a passkey provider's AAGUID, in canonical\n")
	b.WriteString("// lower-case UUID form, to the provider's name.\n")
	b.WriteString("var passkeyProviderNames = map[string]string{\n")
	for _, aaguid := range aaguids {
		fmt.Fprintf(&b, "\t%q: %q,\n", strings.ToLower(aaguid), entries[aaguid].Name)
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format the generated file: %w", err)
	}
	if err := os.WriteFile(output, src, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s: %d providers at %s@%s\n", output, len(aaguids), repo, commit.SHA)
	return nil
}

func getJSON(client *http.Client, url string, v any) error {
	resp, err := client.Get(url)
	if err != nil {
		return err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("GET %s: HTTP %d", url, resp.StatusCode)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 4<<20))
	if err != nil {
		return err
	}
	return json.Unmarshal(body, v)
}
