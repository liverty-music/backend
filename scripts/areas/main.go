// Command areas generates the area and time zone reference data (OpenSpec
// change globalize-venues, Decisions 1 and 2) from pinned CLDR, IANA tzdata
// and Natural Earth releases and the hand-kept files in this directory, and
// writes it as one Atlas migration of upserts that never deletes.
//
// Run it from the repository root:
//
//	go run ./scripts/areas -out k8s/atlas/base/migrations/<version>_seed_areas.sql
//
// then run `atlas migrate hash --env local` and add the file to
// k8s/atlas/base/kustomization.yaml. It refuses to write when a code or zone
// of the previous run (seed.json) would be lost, or when a first-level code
// would stop being first-level; the upgrading change must then remap the
// venues, homes and sales that use it.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const dir = "scripts/areas"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "areas:", err)
		os.Exit(1)
	}
}

func run() error {
	cache, _ := os.UserCacheDir()
	src := flag.String("src", filepath.Join(cache, "liverty-areas", cldrTag+"_"+tzdataVersion+"_"+naturalEarthTag), "directory the pinned sources are downloaded to")
	out := flag.String("out", "", "migration file to write")
	flag.Parse()
	if *out == "" {
		return errors.New("-out is required")
	}

	if err := fetch(*src); err != nil {
		return fmt.Errorf("download the sources: %w", err)
	}
	in, err := readInputs(*src, dir)
	if err != nil {
		return err
	}

	snapPath := filepath.Join(dir, "seed.json")
	var prev *Snapshot
	if b, err := os.ReadFile(snapPath); err == nil {
		prev = &Snapshot{}
		if err := json.Unmarshal(b, prev); err != nil {
			return fmt.Errorf("%s: %w", snapPath, err)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}

	seed, err := Generate(in, prev)
	if err != nil {
		return err
	}
	if err := os.WriteFile(*out, []byte(seed.SQL()), 0o644); err != nil {
		return err
	}
	b, err := json.MarshalIndent(seed.Snapshot(), "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(snapPath, append(b, '\n'), 0o644); err != nil {
		return err
	}

	var first, points, zones int
	for _, a := range seed.Areas {
		if a.FirstLevel() {
			first++
			if a.Reference != nil {
				points++
			}
			if a.TimeZone != "" {
				zones++
			}
		}
	}
	fmt.Printf("wrote %s: %d areas (%d first-level, %d with a reference point, %d with a time zone), %d time zones\n",
		*out, len(seed.Areas), first, points, zones, len(seed.TimeZones))
	return nil
}

// SQL renders the seed as an idempotent migration.
func (s *Seed) SQL() string {
	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by scripts/areas from CLDR %s, IANA tzdata %s and Natural Earth %s.\n", cldrTag, tzdataVersion, naturalEarthTag)
	b.WriteString("-- Do not edit: change the pins or the hand-kept files and run the generator again.\n")
	b.WriteString("SET search_path TO app, public;\n\n")

	b.WriteString("INSERT INTO time_zones (name, name_en, name_ja) VALUES\n")
	for i, z := range s.TimeZones {
		fmt.Fprintf(&b, "  (%s, %s, %s)%s\n", lit(z.Name), lit(z.NameEN), litOrNull(z.NameJA), sep(i, len(s.TimeZones)))
	}
	b.WriteString("ON CONFLICT (name) DO UPDATE SET name_en = EXCLUDED.name_en, name_ja = EXCLUDED.name_ja;\n\n")

	b.WriteString("INSERT INTO country_time_zones (country_code, time_zone) VALUES\n")
	for i, z := range s.CountryZones {
		fmt.Fprintf(&b, "  (%s, %s)%s\n", lit(z.Country), lit(z.Zone), sep(i, len(s.CountryZones)))
	}
	b.WriteString("ON CONFLICT DO NOTHING;\n\n")

	// Areas come parents and replacements first, so every reference exists
	// when its row is written.
	b.WriteString("INSERT INTO areas (code, kind, country_code, parent_code, replaced_by_code, name_en, name_ja, reference_latitude, reference_longitude, reference_point_source, time_zone) VALUES\n")
	for i, a := range s.Areas {
		lat, lng, from := "NULL", "NULL", "NULL"
		if a.Reference != nil {
			lat = strconv.FormatFloat(a.Reference.Lat, 'f', -1, 64)
			lng = strconv.FormatFloat(a.Reference.Lng, 'f', -1, 64)
			from = lit(a.ReferenceFrom)
		}
		fmt.Fprintf(&b, "  (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s\n",
			lit(a.Code), lit(a.Kind), lit(a.CountryCode), litOrNull(a.ParentCode), litOrNull(a.ReplacedByCode),
			lit(a.NameEN), litOrNull(a.NameJA), lat, lng, from, litOrNull(a.TimeZone), sep(i, len(s.Areas)))
	}
	b.WriteString("ON CONFLICT (code) DO UPDATE SET kind = EXCLUDED.kind, country_code = EXCLUDED.country_code, parent_code = EXCLUDED.parent_code, replaced_by_code = EXCLUDED.replaced_by_code, name_en = EXCLUDED.name_en, name_ja = EXCLUDED.name_ja, reference_latitude = EXCLUDED.reference_latitude, reference_longitude = EXCLUDED.reference_longitude, reference_point_source = EXCLUDED.reference_point_source, time_zone = EXCLUDED.time_zone;\n")

	if len(s.Memberships) > 0 {
		b.WriteString("\nINSERT INTO area_memberships (region_code, member_code) VALUES\n")
		for i, m := range s.Memberships {
			fmt.Fprintf(&b, "  (%s, %s)%s\n", lit(m[0]), lit(m[1]), sep(i, len(s.Memberships)))
		}
		b.WriteString("ON CONFLICT DO NOTHING;\n")
	}
	return b.String()
}

func lit(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func litOrNull(s string) string {
	if s == "" {
		return "NULL"
	}
	return lit(s)
}

func sep(i, n int) string {
	if i == n-1 {
		return ""
	}
	return ","
}
