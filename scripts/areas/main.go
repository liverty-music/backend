// Command areas generates the area and time zone reference data (OpenSpec
// change globalize-venues, Decisions 1 and 2) from pinned CLDR, IANA tzdata
// and Natural Earth releases and the hand-kept files in this directory, and
// writes it as one migration of upserts that never deletes: the whole seed
// on the first run, only the rows that changed since seed.json afterwards.
// The migration goes to the reference data directory, which the
// backend-reference-data AtlasMigration applies after the schema migrations
// (it does not fit the schema migrations' ConfigMap).
//
// Run it from the repository root:
//
//	go run ./scripts/areas -out k8s/atlas/base/reference-data/<version>_seed_areas.sql
//
// then run `atlas migrate hash --dir file://k8s/atlas/base/reference-data` and
// add the file to k8s/atlas/base/kustomization.yaml. It refuses to write when a code or zone
// of the previous run (seed.json) would be lost, or when a first-level code
// would stop being first-level; the upgrading change must then remap the
// venues, homes and sales that use it.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const dir = "scripts/areas"

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "areas:", err)
		os.Exit(1)
	}
}

func run() error {
	cache, _ := os.UserCacheDir()
	src := flag.String("src", filepath.Join(cache, "liverty-areas", cldrTag+"_"+tzdataVersion+"_"+naturalEarthTag), "directory the pinned sources are downloaded to")
	out := flag.String("out", "", "migration file to write")
	flag.Parse()
	if *out == "" {
		return errors.New("-out is required")
	}

	if err := fetch(*src); err != nil {
		return fmt.Errorf("download the sources: %w", err)
	}
	in, err := readInputs(*src, dir)
	if err != nil {
		return err
	}

	snapPath := filepath.Join(dir, "seed.json")
	prev, err := readSnapshot(snapPath)
	if err != nil {
		return err
	}

	seed, err := Generate(in, prev)
	if err != nil {
		return err
	}
	delta := seed.Since(prev)
	if delta.Empty() {
		fmt.Println("nothing changed since the previous seed; no file written")
		return nil
	}
	if err := os.WriteFile(*out, []byte(delta.SQL()), 0o644); err != nil {
		return err
	}
	b, err := json.MarshalIndent(seed.Snapshot(), "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(snapPath, append(b, '\n'), 0o644); err != nil {
		return err
	}

	fmt.Printf("wrote %s: %d of %d areas changed; %s\n", *out, len(delta.Areas), len(seed.Areas), seed.summary())
	return nil
}

// readSnapshot reads the previous run's snapshot; nil when there was none.
func readSnapshot(path string) (*Snapshot, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var snap Snapshot
	if err := json.Unmarshal(b, &snap); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &snap, nil
}

func (s *Seed) summary() string {
	var first, points, zones int
	for _, a := range s.Areas {
		if !a.FirstLevel() {
			continue
		}
		first++
		if a.Reference != nil {
			points++
		}
		if a.TimeZone != "" {
			zones++
		}
	}
	return fmt.Sprintf("the seed has %d first-level areas, %d with a reference point, %d with a time zone, and %d time zones",
		first, points, zones, len(s.TimeZones))
}

// SQL renders the seed as an idempotent migration. Each statement is left
// out when it has no rows.
func (s *Seed) SQL() string {
	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by scripts/areas from CLDR %s, IANA tzdata %s and Natural Earth %s.\n", cldrTag, tzdataVersion, naturalEarthTag)
	b.WriteString("-- Do not edit: change the pins or the hand-kept files and run the generator again.\n")
	b.WriteString("SET search_path TO app, public;\n")

	upsert := func(head string, rows []string, conflict string) {
		if len(rows) == 0 {
			return
		}
		b.WriteString("\n" + head + " VALUES\n")
		for i, r := range rows {
			b.WriteString("  " + r + sep(i, len(rows)) + "\n")
		}
		b.WriteString(conflict + ";\n")
	}
	var rows []string
	for _, z := range s.TimeZones {
		rows = append(rows, zoneValues(z))
	}
	upsert("INSERT INTO time_zones (name, name_en, name_ja)", rows,
		"ON CONFLICT (name) DO UPDATE SET name_en = EXCLUDED.name_en, name_ja = EXCLUDED.name_ja")

	rows = nil
	for _, z := range s.CountryZones {
		rows = append(rows, "("+lit(z.Country)+", "+lit(z.Zone)+")")
	}
	upsert("INSERT INTO country_time_zones (country_code, time_zone)", rows, "ON CONFLICT DO NOTHING")

	// Areas come parents and replacements first.
	rows = nil
	for _, a := range s.Areas {
		rows = append(rows, areaValues(a))
	}
	upsert("INSERT INTO areas (code, kind, country_code, parent_code, replaced_by_code, name_en, name_ja, reference_latitude, reference_longitude, reference_point_source, time_zone)", rows,
		"ON CONFLICT (code) DO UPDATE SET kind = EXCLUDED.kind, country_code = EXCLUDED.country_code, parent_code = EXCLUDED.parent_code, replaced_by_code = EXCLUDED.replaced_by_code, name_en = EXCLUDED.name_en, name_ja = EXCLUDED.name_ja, reference_latitude = EXCLUDED.reference_latitude, reference_longitude = EXCLUDED.reference_longitude, reference_point_source = EXCLUDED.reference_point_source, time_zone = EXCLUDED.time_zone")

	rows = nil
	for _, m := range s.Memberships {
		rows = append(rows, "("+lit(m[0])+", "+lit(m[1])+")")
	}
	upsert("INSERT INTO area_memberships (region_code, member_code)", rows, "ON CONFLICT DO NOTHING")
	return b.String()
}

// zoneValues renders a time_zones row.
func zoneValues(z TimeZone) string {
	return "(" + lit(z.Name) + ", " + lit(z.NameEN) + ", " + litOrNull(z.NameJA) + ")"
}

// areaValues renders an areas row.
func areaValues(a Area) string {
	lat, lng, from := "NULL", "NULL", "NULL"
	if a.Reference != nil {
		lat = strconv.FormatFloat(a.Reference.Lat, 'f', -1, 64)
		lng = strconv.FormatFloat(a.Reference.Lng, 'f', -1, 64)
		from = lit(a.ReferenceFrom)
	}
	return "(" + strings.Join([]string{
		lit(a.Code), lit(a.Kind), lit(a.CountryCode), litOrNull(a.ParentCode), litOrNull(a.ReplacedByCode),
		lit(a.NameEN), litOrNull(a.NameJA), lat, lng, from, litOrNull(a.TimeZone),
	}, ", ") + ")"
}

func lit(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func litOrNull(s string) string {
	if s == "" {
		return "NULL"
	}
	return lit(s)
}

func sep(i, n int) string {
	if i == n-1 {
		return ""
	}
	return ","
}
