// outboxPool returns a pool whose search path is a schema of its own holding
// an empty outbox table, so the report reads only the rows this test writes.
func outboxPool(t *testing.T) *pgxpool.Pool {
	t.Helper()
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, fmt.Sprintf(adminDSNFormat, testDBPort()))
	if err != nil {
		t.Skipf("no local database available: %v", err)
	}
	defer func() { _ = admin.Close(ctx) }()
	schema := "undelivered_test_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	_, err = admin.Exec(ctx, fmt.Sprintf(`
		CREATE SCHEMA %[1]s;
		CREATE TABLE %[1]s.watermill_events_outbox (
			"offset" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			uuid TEXT NOT NULL,
			payload JSON DEFAULT NULL,
			metadata JSON DEFAULT NULL,
			acked BOOLEAN NOT NULL DEFAULT FALSE,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		)`, schema))
	require.NoError(t, err)
	t.Cleanup(func() {
		conn, err := pgx.Connect(context.Background(), fmt.Sprintf(adminDSNFormat, testDBPort()))
		if err == nil {
			_, _ = conn.Exec(context.Background(), fmt.Sprintf(`DROP SCHEMA %s CASCADE`, schema))
			_ = conn.Close(context.Background())
		}
	})
	cfg, err := pgxpool.ParseConfig(fmt.Sprintf(adminDSNFormat, testDBPort()))
	require.NoError(t, err)
	cfg.ConnConfig.RuntimeParams["search_path"] = schema
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	require.NoError(t, err)
	t.Cleanup(pool.Close)
	return pool
}

// @spec components/infrastructure/backend/process/event-delivery "Broker unreachable"
func TestAdmin_ReportsTheOldestUndeliveredAnnouncement(t *testing.T) {
	ctx := context.Background()
	pool := outboxPool(t)
	logger, logs := newLogger(t)
	now := time.Date(2026, 10, 30, 12, 0, 0, 0, time.UTC)

	age, err := workflow.ReportUndelivered(ctx, logger, pool, now)
	require.NoError(t, err)
	assert.Zero(t, age, "an empty outbox reports 0")

	_, err = pool.Exec(ctx, `INSERT INTO watermill_events_outbox (uuid, payload, created_at) VALUES ('a', '{"destination_topic":"ARTIST.followed"}', $1)`, now.Add(-11*time.Minute))
	require.NoError(t, err)

	age, err = workflow.ReportUndelivered(ctx, logger, pool, now)
	require.NoError(t, err)
	assert.Greater(t, age, 600.0)
	assert.Contains(t, logs.String(), workflow.LogKeyAnnouncementUndelivered)
	assert.Contains(t, logs.String(), "ARTIST.followed")
}
